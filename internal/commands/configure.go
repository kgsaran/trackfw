package commands

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/charmbracelet/huh"
	"github.com/spf13/cobra"

	"github.com/kgsaran/trackfw/internal/pathguard"
)

// configureGetwdFn is the function used to obtain the current working directory
// inside the configure command's write guard. It defaults to os.Getwd and may be
// overridden in tests to inject a controlled failure without relying on OS-specific
// filesystem tricks (e.g. removing the CWD, which Windows prevents while the
// directory is in use).
var configureGetwdFn func() (string, error) = os.Getwd

const configureYAMLHeader = "# trackfw.yaml — generated by trackfw configure\n"

func newConfigureCmd() *cobra.Command {
	return &cobra.Command{
		Use:   "configure",
		Short: "Interactive wizard to create or recreate trackfw.yaml",
		Long: `Interactive wizard that guides the configuration of trackfw.yaml.
Generates a sparse file: only fields that differ from defaults are written.`,
		RunE: func(cmd *cobra.Command, args []string) error {
			// Verificar se trackfw.yaml já existe
			if _, err := os.Stat("trackfw.yaml"); err == nil {
				var action string
				confirm := huh.NewForm(
					huh.NewGroup(
						huh.NewSelect[string]().
							Title("trackfw.yaml already exists. What would you like to do?").
							Options(
								huh.NewOption("Recreate from scratch", "recreate"),
								huh.NewOption("Cancel", "cancel"),
							).
							Value(&action),
					),
				)
				if err := confirm.Run(); err != nil {
					return fmt.Errorf("wizard error: %w", err)
				}
				if action == "cancel" {
					fmt.Println("Operation cancelled.")
					return nil
				}
			}

			// Campos principais
			var (
				adrDirsRaw  = "docs/adr"
				reqDir      = "docs/req"
				roadmapDir  = "docs/roadmaps"
				wipLimitStr = "1"
				reqMarker   = "REQ:"
			)

			mainForm := huh.NewForm(
				huh.NewGroup(
					huh.NewInput().
						Title("ADR directories (comma-separated)").
						Placeholder("docs/adr").
						Value(&adrDirsRaw),
					huh.NewInput().
						Title("REQ directory").
						Placeholder("docs/req").
						Value(&reqDir),
					huh.NewInput().
						Title("Roadmaps root directory").
						Placeholder("docs/roadmaps").
						Value(&roadmapDir),
					huh.NewInput().
						Title("Simultaneous WIP item limit").
						Placeholder("1").
						Value(&wipLimitStr),
				),
				huh.NewGroup(
					huh.NewInput().
						Title("Inline REQ marker (e.g. REQ: or req_id:)").
						Placeholder("REQ:").
						Value(&reqMarker),
				),
			)

			if err := mainForm.Run(); err != nil {
				return fmt.Errorf("wizard error: %w", err)
			}

			// Processar valores
			adrDirs := parseCommaSeparated(adrDirsRaw)
			wipLimit, err := strconv.Atoi(strings.TrimSpace(wipLimitStr))
			if err != nil || wipLimit < 1 {
				wipLimit = 1
			}

			// Defaults de comparação
			defaultAdrDirs := []string{"docs/adr"}
			defaultReqDir := "docs/req"
			defaultRoadmapDir := "docs/roadmaps"
			defaultWipLimit := 1
			defaultReqMarker := "REQ:"

			// Construir config esparsa
			var lines []string
			customCount := 0

			if !stringSliceEqual(adrDirs, defaultAdrDirs) {
				lines = append(lines, "adr_dirs:")
				for _, d := range adrDirs {
					lines = append(lines, "  - "+d)
				}
				customCount++
			}

			if strings.TrimSpace(reqDir) != defaultReqDir {
				lines = append(lines, "req_dir: "+strings.TrimSpace(reqDir))
				customCount++
			}

			if strings.TrimSpace(roadmapDir) != defaultRoadmapDir {
				lines = append(lines, "roadmap_dir: "+strings.TrimSpace(roadmapDir))
				customCount++
			}

			if wipLimit != defaultWipLimit {
				lines = append(lines, fmt.Sprintf("wip_limit: %d", wipLimit))
				customCount++
			}

			if strings.TrimSpace(reqMarker) != defaultReqMarker {
				lines = append(lines, "link_fields:")
				lines = append(lines, "  req:")
				lines = append(lines, "    - \""+strings.TrimSpace(reqMarker)+"\"")
				customCount++
			}

			// Gravar arquivo
			var content string
			content = configureYAMLHeader
			if len(lines) > 0 {
				content += strings.Join(lines, "\n") + "\n"
			}

			// Guard before write: resolve project root from CWD, then reject any
			// symlink ancestor between root and trackfw.yaml. Guard precedes write
			// (and any MkdirAll) so a refused destination creates no stray file.
			// Root: EvalSymlinks(Getwd()) — macOS /tmp→/private/tmp invariant.
			// Fail closed: if Getwd() fails we cannot verify containment, so we refuse the write.
			configureRoot, cwdErr := configureGetwdFn()
			if cwdErr != nil {
				return pathguard.RefuseUnverifiableRoot("trackfw.yaml", cwdErr)
			}
			if resolved, resolveErr := filepath.EvalSymlinks(configureRoot); resolveErr == nil {
				configureRoot = resolved
			}
			absYAML := filepath.Join(configureRoot, "trackfw.yaml")
			if guardErr := pathguard.RejectAndReport(configureRoot, absYAML); guardErr != nil {
				return guardErr
			}
			// write-containment-allowed: guarded by pathguard.RejectSymlinks above (fail-closed on Getwd error)
			if err := os.WriteFile("trackfw.yaml", []byte(content), 0644); err != nil {
				return fmt.Errorf("error writing trackfw.yaml: %w", err)
			}

			fmt.Printf("trackfw.yaml written with %d customized fields\n", customCount)
			return nil
		},
	}
}

// parseCommaSeparated divide string por vírgula e remove espaços.
func parseCommaSeparated(s string) []string {
	parts := strings.Split(s, ",")
	var result []string
	for _, p := range parts {
		p = strings.TrimSpace(p)
		if p != "" {
			result = append(result, p)
		}
	}
	if len(result) == 0 {
		return []string{"docs/adr"}
	}
	return result
}

// stringSliceEqual compara duas slices de string.
func stringSliceEqual(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}
