// Package opencodeplugin embeds the trackfw-guard.js OpenCode plugin asset and
// exposes Render(scope) for callers (generators, validator) that need the
// canonical content. It is a leaf package — no internal/ imports — so both
// internal/generators and internal/validator can import it without a cycle.
//
// The asset is the product version of the plugin (no probe log, hook_source
// included). The only difference between project and global is the SCOPE
// constant on line `const SCOPE = "project"`.
//
// D1 (ADR-2026-11-19): the asset begins with `// trackfw:opencode-guard`
// (Marker). The validator uses this string to detect and authenticate the
// plugin. If the string is absent, the file was not generated by trackfw.
package opencodeplugin

import (
	"bytes"
	_ "embed"
	"fmt"
	"strings"
)

// Marker is the first-line sentinel written at the top of every generated
// trackfw-guard.js. The validator uses it to distinguish trackfw-managed
// files from third-party plugins and to detect tampering.
const Marker = "// trackfw:opencode-guard"

// PluginRelPath is the project-scope relative path of the OpenCode guard plugin
// within a trackfw project. Use this constant instead of a local literal so that
// every caller stays in sync when the path changes (A4).
const PluginRelPath = ".opencode/plugins/trackfw-guard.js"

// projectScopeToken is the exact string in the asset that carries the scope
// value. Render replaces it once to produce the global variant.
const projectScopeToken = `const SCOPE = "project"`

// globalScopeToken is the replacement used for the global plugin.
const globalScopeToken = `const SCOPE = "global"`

//go:embed trackfw-guard.js
var assetBytes []byte

// Render returns the canonical plugin content for the given scope.
//
// scope must be "project" or "global". Any other value returns an error.
//
// The function validates that projectScopeToken appears exactly once in the
// asset (D3 of the in-code design contract): a whitespace edit to the asset
// that removes or duplicates the token would cause Render to fail loudly
// rather than silently producing an incorrect global variant.
func Render(scope string) ([]byte, error) {
	switch scope {
	case "project":
		return bytes.Clone(assetBytes), nil
	case "global":
		src := string(assetBytes)
		count := strings.Count(src, projectScopeToken)
		if count != 1 {
			return nil, fmt.Errorf(
				"opencodeplugin: asset invariant broken — projectScopeToken appears %d times (want exactly 1); asset must be repaired",
				count,
			)
		}
		return []byte(strings.Replace(src, projectScopeToken, globalScopeToken, 1)), nil
	default:
		return nil, fmt.Errorf("opencodeplugin.Render: unknown scope %q (want \"project\" or \"global\")", scope)
	}
}

// RenderProject returns the canonical project-scope plugin content.
// It panics if the asset invariant (single projectScopeToken) is violated —
// this would only happen if the embedded asset is malformed.
func RenderProject() []byte {
	b, err := Render("project")
	if err != nil {
		panic("opencodeplugin.RenderProject: " + err.Error())
	}
	return b
}

// RenderGlobal returns the canonical global-scope plugin content.
// It panics if the asset invariant is violated.
func RenderGlobal() []byte {
	b, err := Render("global")
	if err != nil {
		panic("opencodeplugin.RenderGlobal: " + err.Error())
	}
	return b
}
