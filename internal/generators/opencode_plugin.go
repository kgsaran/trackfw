package generators

import (
	"os"
	"path/filepath"

	"github.com/kgsaran/trackfw/internal/integrations"
	"github.com/kgsaran/trackfw/internal/opencodeplugin"
	"github.com/kgsaran/trackfw/internal/pathguard"
)

// openCodePluginRelPath is the project-scope relative path of the OpenCode
// guard plugin within a project root. ADR-2026-11-19 D5.
const openCodePluginRelPath = ".opencode/plugins/trackfw-guard.js"

// InjectOpenCodePlugin writes (or refreshes) the trackfw guard plugin for
// OpenCode at <rootDir>/.opencode/plugins/trackfw-guard.js using the
// canonical project-scope content from internal/opencodeplugin.
//
// The function is idempotent and safe to call more than once:
//   - If the file is absent, it is created.
//   - If the file is present and starts with opencodeplugin.Marker AND its
//     content matches the current canonical render (after CRLF normalisation),
//     the file is left unchanged (no-op).
//   - If the file is present but its content differs from the canonical render
//     (stale) or lacks the marker (not generated by trackfw), it is overwritten.
//   - Writes through symlinks are rejected by pathguard.RejectAndReport before
//     any filesystem mutation.
//
// ADR-2026-11-19 D1 / D5.
func InjectOpenCodePlugin(rootDir string) error {
	// ML-8A: resolve root so the pathguard namespace is consistent.
	guardRoot, rootErr := pathguard.ResolveRoot(rootDir)
	if rootErr != nil {
		return pathguard.RefuseUnverifiableRoot(filepath.Join(rootDir, openCodePluginRelPath), rootErr)
	}

	path := filepath.Join(guardRoot, openCodePluginRelPath)
	if guardErr := pathguard.RejectAndReport(guardRoot, path); guardErr != nil {
		return guardErr
	}

	// Canonical content for the project-scope variant.
	canonical := opencodeplugin.RenderProject()
	canonical = integrations.NormalizeCRLF(canonical)

	// Check whether the existing file already matches the canonical render.
	raw, err := os.ReadFile(path)
	if err == nil {
		normalised := integrations.NormalizeCRLF(raw)
		if string(normalised) == string(canonical) {
			return nil // already up-to-date
		}
	} else if !os.IsNotExist(err) {
		return err
	}

	// write-containment-allowed: guarded by pathguard.RejectSymlinks at the enclosing write site
	if mkErr := os.MkdirAll(filepath.Dir(path), 0755); mkErr != nil {
		return mkErr
	}
	// write-containment-allowed: guarded by pathguard.RejectSymlinks at the enclosing write site
	return os.WriteFile(path, canonical, 0644)
}
