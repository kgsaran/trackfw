// TestWrongModeDetection_ContentDivergence_TakesPrecedence verifies that a file
// with both wrong content and wrong mode produces scaffold-divergent, not
// scaffold-wrong-mode (content divergence takes precedence — AC3).
func TestWrongModeDetection_ContentDivergence_TakesPrecedence(t *testing.T) {
	// No platform guard here, on purpose: checkScaffoldArtifact checks
	// content BEFORE the execute bit (bytes.Equal at scaffold_doctor.go
	// precedes the CurrentGOOS/execBitPresent branch), so this assertion
	// never touches the execute bit and holds unconditionally on every
	// platform. A t.Skip("execute bit not applicable...") here was
	// leftover copy-paste from the neighboring mode tests, not a real
	// platform dependency — see the ML-1A scan report.
	dir := t.TempDir()
	relPath := "scripts/trackfw-attention-signal.sh"
	p := filepath.Join(dir, relPath)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	// Wrong content AND wrong mode.
	if err := os.WriteFile(p, []byte("wrong content\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(p, 0o644); err != nil {
		t.Fatal(err)
	}

	finding := checkScaffoldArtifact(p, relPath, []byte(attentionSignalScript), true, true)
	if finding == nil {
		t.Fatal("expected a finding, got nil")
	}
	if finding.FindingKind != integrations.DoctorScaffoldDivergent {
		t.Errorf("expected scaffold-divergent (content takes precedence), got %q", finding.FindingKind)
	}
}

// TestExecBitFalse_NotAccusedForMissingBit verifies AC4/AC11: an artifact with
// execBit=false is never accused of a missing execute bit, even when at 0644.
func TestExecBitFalse_NotAccusedForMissingBit(t *testing.T) {
	dir := t.TempDir()
	relPath := ".claude/commands/trackfw/example.md"
	p := filepath.Join(dir, relPath)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	content := "# example slash command\n"
	// Write with 0644 (no execute bit) — correct for this artifact type.
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}

	finding := checkScaffoldArtifact(p, relPath, []byte(content), true, false)
	if finding != nil {
		t.Errorf("expected no finding for 0644 non-executable artifact, got: %+v", finding)
	}
}

