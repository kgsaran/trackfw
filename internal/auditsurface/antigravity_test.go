// TestExtractTuplesAntigravity asserts:
// extractTuples("antigravity", content) returns exactly 4 HookTuples from a
// .agents/hooks.json generated by InjectAntigravityHooks, with the git-branch
// tuple carrying literal matcher "run_command" and the three credential tuples
// carrying "run_command|manage_task", "view_file", and
// "write_to_file|replace_file_content|multi_replace_file_content" respectively.
func TestExtractTuplesAntigravity(t *testing.T) {
	dir := t.TempDir()
	t.Setenv("CODEX_HOME", "")
	t.Setenv("HOME", dir)
	t.Setenv("USERPROFILE", dir)

	if err := generators.InjectAntigravityHooks(dir); err != nil {
		t.Fatalf("InjectAntigravityHooks: %v", err)
	}

	content, err := os.ReadFile(filepath.Join(dir, ".agents", "hooks.json"))
	if err != nil {
		t.Fatalf("read hooks.json: %v", err)
	}

	tuples, err := extractTuples("antigravity", content)
	if err != nil {
		t.Fatalf("extractTuples: %v", err)
	}

	// D5 contract: exactly 4 tuples (3 credential + 1 git-branch).
	if len(tuples) != 4 {
		t.Errorf("tuple count = %d, want 4", len(tuples))
		for i, tup := range tuples {
			t.Logf("  [%d] event=%q matcher=%q command=%q", i, tup.Event, tup.Matcher, tup.RawCommand)
		}
	}

	// Sort order from extractAntigravitySchema: matchers are sorted alphabetically.
	// Expected order:
	//   [0] run_command           → git-branch
	//   [1] run_command|manage_task → credential
	//   [2] view_file             → credential
	//   [3] write_to_file|...     → credential
	type wantTuple struct {
		event   string
		matcher string
		command string
	}
	wants := []wantTuple{
		{"PreToolUse", "run_command", guardforms.GitBranchCurrentCmdExe},
		{"PreToolUse", "run_command|manage_task", guardforms.CredentialCurrentCmdExe},
		{"PreToolUse", "view_file", guardforms.CredentialCurrentCmdExe},
		{"PreToolUse", "write_to_file|replace_file_content|multi_replace_file_content", guardforms.CredentialCurrentCmdExe},
	}

	for i, w := range wants {
		if i >= len(tuples) {
			t.Errorf("[%d] tuple missing (want event=%q matcher=%q)", i, w.event, w.matcher)
			continue
		}
		got := tuples[i]
		if got.Event != w.event {
			t.Errorf("[%d] event = %q, want %q", i, got.Event, w.event)
		}
		if got.Matcher != w.matcher {
			t.Errorf("[%d] matcher = %q, want %q", i, got.Matcher, w.matcher)
		}
		if got.RawCommand != w.command {
			t.Errorf("[%d] command = %q, want %q", i, got.RawCommand, w.command)
		}
	}

	// Explicit: git-branch must NOT appear at run_command|manage_task.
	for _, tup := range tuples {
		if tup.Matcher == "run_command|manage_task" && tup.RawCommand == guardforms.GitBranchCurrentCmdExe {
			t.Errorf("git-branch command found at run_command|manage_task (wrong matcher — ML-3B corretivo regression)")
		}
	}
}
